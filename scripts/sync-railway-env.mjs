#!/usr/bin/env node
/**
 * Write Railway-only client env files for web + both mobile apps.
 * No local Medusa — config/railway-client.json is the source of truth.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const cfg = JSON.parse(fs.readFileSync(path.join(ROOT, 'config/railway-client.json'), 'utf8'));

if (/localhost|127\.0\.0\.1/i.test(cfg.medusaBase)) {
  console.error('ERROR: config/railway-client.json must use Railway URL, not localhost.');
  process.exit(1);
}

const targets = [
  {
    path: 'apps/mobile-customer/.env.local',
    body: [
      '# Railway-only backend — generated by pnpm env:sync',
      `EXPO_PUBLIC_MEDUSA_BASE=${cfg.medusaBase}`,
      `EXPO_PUBLIC_MEDUSA_PUBLISHABLE_KEY=${cfg.publishableKey}`,
      '',
    ].join('\n'),
  },
  {
    path: 'apps/mobile-cook/.env.local',
    body: [
      '# Railway-only backend — generated by pnpm env:sync',
      `EXPO_PUBLIC_MEDUSA_BASE=${cfg.medusaBase}`,
      `EXPO_PUBLIC_MEDUSA_PUBLISHABLE_KEY=${cfg.publishableKey}`,
      '',
    ].join('\n'),
  },
  {
    path: 'apps/web/.env.local',
    body: [
      '# Railway-only backend — generated by pnpm env:sync',
      `NEXT_PUBLIC_SHC_API_BASE=${cfg.medusaBase}`,
      `NEXT_PUBLIC_MEDUSA_PUBLISHABLE_KEY=${cfg.publishableKey}`,
      '',
    ].join('\n'),
  },
];

for (const t of targets) {
  const out = path.join(ROOT, t.path);
  fs.writeFileSync(out, t.body);
  console.log(`✓ ${t.path}`);
}

console.log(`\nAll clients → ${cfg.medusaBase}`);